// Regenerates lib/data/labs/existence.ts — a lightweight "does this
// academy/technology have real Labs content" index, derived from the
// actual lib/data/labs/* data files instead of hand-maintained.
//
// Why this exists as a separate generated index rather than importing the
// labs data files directly wherever "does this tech have labs" is needed:
// lib/data/labs/*.ts files are large (devops.ts alone is 2000+ lines of
// lab step data) and get imported by client components (WhatNext.tsx,
// MobileSectionNav.tsx) as well as server ones. Checking existence via a
// direct import would pull that entire dataset into those client bundles
// just to answer a boolean. This script does the lookup once, at build
// time, and writes out just the O(1) answer -- same pattern as
// generate-content-registry.mjs's contentRegistry.
//
// Run with: npm run generate:labs-existence
// Re-run any time lib/data/labs/*.ts content changes.

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildSync } from "esbuild";
import { createRequire } from "node:module";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";

const require = createRequire(import.meta.url);
const ROOT = process.cwd();
const OUTPUT_PATH = join(ROOT, "lib/data/labs/existence.ts");

function loadModule(entryPoint) {
  const tmpDir = mkdtempSync(join(tmpdir(), "synfracore-labs-gen-"));
  const outFile = join(tmpDir, "mod.cjs");
  try {
    const result = buildSync({ entryPoints: [entryPoint], bundle: true, platform: "node", format: "cjs", write: false });
    writeFileSync(outFile, result.outputFiles[0].contents);
    return require(outFile);
  } finally {
    rmSync(tmpDir, { recursive: true, force: true });
  }
}

const { getAllTechnologies } = loadModule(join(ROOT, "lib/data/academies.ts"));

// Mirrors LAB_GROUP in components/tech/LabsSection.tsx -- which academy's
// technologies are covered by which lib/data/labs/*.ts file. Keep these
// two maps in sync; if LabsSection.tsx's LAB_GROUP gains a new academy,
// add it here too or this generator will silently mark that academy's
// labs as nonexistent.
const LAB_GROUP = {
  devops: "devops", cloud: "cloud", databases: "databases",
  ai: "ai", data: "data", security: "security",
  education: "education",
};

const moduleCache = new Map();
function getLabsModule(group) {
  if (!moduleCache.has(group)) {
    moduleCache.set(group, loadModule(join(ROOT, `lib/data/labs/${group}.ts`)));
  }
  return moduleCache.get(group);
}

const existence = new Set();
let checked = 0;
for (const t of getAllTechnologies()) {
  const group = LAB_GROUP[t.academy];
  if (!group) continue; // academy has no labs data file at all -- correctly absent
  checked++;
  const { getLabsForTech } = getLabsModule(group);
  const labs = getLabsForTech(t.slug);
  if (Array.isArray(labs) && labs.length > 0) {
    existence.add(`${t.academy}/${t.slug}`);
    console.log(`  has labs: ${t.academy}/${t.slug} (${labs.length})`);
  }
}

const sortedKeys = [...existence].sort();
const lines = sortedKeys.map((k) => `  "${k}",`).join("\n");

const output = `// Generated by scripts/generate-labs-existence.mjs — do not hand-edit.
// Run "npm run generate:labs-existence" after changing lib/data/labs/*.ts;
// this is a lightweight existence index (not the lab content itself) so
// callers can check "does this technology have real labs" without
// importing the (large) lab data files themselves.
export const labsExistence = new Set<string>([
${lines}
]);

export function hasLabsContent(academySlug: string, technologySlug: string): boolean {
  return labsExistence.has(\`\${academySlug}/\${technologySlug}\`);
}
`;

writeFileSync(OUTPUT_PATH, output);

console.log(`\nDone. ${checked} technologies checked across ${Object.keys(LAB_GROUP).length} lab-covered academies -> ${existence.size} have real labs content.`);
