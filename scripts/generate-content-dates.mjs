// Generates lib/content/last-updated.ts from real git commit history instead
// of a hand-maintained date. Fixes a real, live bug: components/tech/
// AuthorBadge.tsx rendered a hardcoded "Updated 2025" literal on every
// single content page site-wide, regardless of the actual file's history —
// already stale by the time it was found (see memory
// project_future_phase_section_nav_byline_cleanup.md, Item 2's "bonus bug").
//
// A hand-typed date has the same failure mode as the one already caught
// live on /terms ("Last updated: January 2025" shown months after the real
// edit) — it's correct once, at the moment someone remembers to type it,
// and silently wrong forever after. Deriving the date from git history
// instead means it can never drift: it IS the actual last commit that
// touched the file.
//
// What it does: one single `git log --name-only` walk over public/content/
// history (not one subprocess per file — 2580+ files would make a
// per-file approach slow), newest-commit-first. The first time a given
// file path is seen walking newest-to-oldest is its most recent commit.
//
// Known limitation (documented, not hidden): this reflects when a file's
// *content last changed*, not when its facts were last verified — a typo
// fix bumps the date the same as a substantive rewrite. A file that was
// renamed (e.g. the infrastructure -> devops slug rename) only accumulates
// history under its current path in this walk, which is still correct for
// "last modified" purposes (the most recent real commit under the current
// path), even though it wouldn't show the file's full pre-rename history.
//
// Run with: npm run generate:content-dates
// Re-run any time content changes — safe to run repeatedly, and should be
// re-run (and diffed) before each deploy, same discipline as
// generate:content-registry.
//
// Fails gracefully, on purpose (2026-08-30 incident): this originally used
// a bare execSync with no error handling, and a build environment missing
// .git (the native WSL build dir, whose rsync used to exclude it) crashed
// with an uncaught exception — which, chained via `&&` in `pages:build`,
// stopped the ENTIRE build, blocking every deploy on a missing date source.
// A last-updated badge is a nice-to-have; it must never be able to take
// down the whole site's ability to deploy. If git history isn't available
// for any reason, this logs a clear warning and exits 0 WITHOUT touching
// lib/content/last-updated.ts — the rest of pages:build continues, and the
// site falls back to whatever last-updated.ts is already committed/present
// (slightly stale dates, not a missing file or a broken build).

import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const CONTENT_PREFIX = "public/content/";

let raw;
try {
  raw = execSync(
    `git log --name-only --no-renames --pretty=format:"C|%H|%cI" -- ${CONTENT_PREFIX}`,
    { cwd: ROOT, maxBuffer: 1024 * 1024 * 256, encoding: "utf8" }
  );
} catch (err) {
  console.warn("WARNING: generate-content-dates.mjs could not read git history — skipping date generation.");
  console.warn(`  Reason: ${err.message.split("\n")[0]}`);
  console.warn("  lib/content/last-updated.ts left untouched (using whatever is already committed/present).");
  console.warn("  This does NOT fail the build — but it means last-updated dates may be stale until this is fixed.");
  process.exit(0);
}

try {
  const lastUpdated = new Map(); // relPath (no prefix, no .md) -> { date, hash }
  let currentHash = null;
  let currentDate = null;

  for (const line of raw.split("\n")) {
    if (line.startsWith("C|")) {
      const [, hash, date] = line.split("|");
      currentHash = hash;
      currentDate = date;
      continue;
    }
    const path = line.trim();
    if (!path.startsWith(CONTENT_PREFIX) || !path.endsWith(".md")) continue;
    const relPath = path.slice(CONTENT_PREFIX.length, -3);
    if (!lastUpdated.has(relPath)) {
      lastUpdated.set(relPath, { date: currentDate.slice(0, 10), hash: currentHash.slice(0, 7) });
    }
  }

  const sortedKeys = [...lastUpdated.keys()].sort();
  const entryLines = sortedKeys
    .map((k) => {
      const { date, hash } = lastUpdated.get(k);
      return `  ["${k}",{"date":"${date}","hash":"${hash}"}],`;
    })
    .join("\n");

  const output = `// Generated by scripts/generate-content-dates.mjs — do not hand-edit.
// Run "npm run generate:content-dates" after content changes; re-run and
// diff before each deploy, same discipline as generate:content-registry.
// Keyed by the PHYSICAL file path (the content registry's value side,
// e.g. "devops/terraform/overview" or its "infrastructure/terraform/overview"
// alias target) — not the registry key — since the date belongs to the
// actual file on disk, independent of how many registry keys alias to it.
const contentLastUpdated = new Map<string, { date: string; hash: string }>([
${entryLines}
]);

export function getLastUpdated(filePath: string): { date: string; hash: string } | null {
  return contentLastUpdated.get(filePath) || null;
}
`;

  writeFileSync(join(ROOT, "lib/content/last-updated.ts"), output);

  console.log(`Done. ${lastUpdated.size} content files mapped to a real git-derived last-updated date.`);
} catch (err) {
  console.warn("WARNING: generate-content-dates.mjs failed while parsing/writing — skipping date generation.");
  console.warn(`  Reason: ${err.message.split("\n")[0]}`);
  console.warn("  lib/content/last-updated.ts left untouched (using whatever is already committed/present).");
  process.exit(0);
}
